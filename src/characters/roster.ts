/** Move count helper for QA */
export function rosterMoveCounts(): Record<FighterId, number> {
  const out = {} as Record<FighterId, number>;
  for (const id of Object.keys(CHARACTER_ROSTER) as FighterId[]) {
    out[id] = Object.keys(CHARACTER_ROSTER[id].moves).length;
  }
  return out;
}
